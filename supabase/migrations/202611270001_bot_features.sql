-- J.A.R.V.I.S. Movie Bot feature tables
create table if not exists public.bot_admins (
  wa_jid text primary key,
  permissions text[] not null default '{}',
  added_by text not null,
  created_at timestamptz not null default now()
);

create table if not exists public.bot_settings (
  setting_key text primary key,
  setting_value text not null default '',
  updated_by text not null,
  updated_at timestamptz not null default now()
);

create table if not exists public.user_library (
  id bigint generated by default as identity primary key,
  wa_jid text not null,
  list_type text not null check (list_type in ('favorite', 'watchlist')),
  media_id text not null,
  media_type text not null default 'movie' check (media_type in ('movie', 'tv')),
  title text not null,
  release_year integer,
  rating text,
  poster_url text,
  source_url text,
  created_at timestamptz not null default now(),
  unique (wa_jid, list_type, media_id, media_type)
);

create index if not exists user_library_jid_type_idx
  on public.user_library (wa_jid, list_type, created_at desc);

-- This service uses the Supabase service-role key only on the Railway server.
-- Do not expose the service-role key in frontend/client applications.
alter table public.bot_admins enable row level security;
alter table public.bot_settings enable row level security;
alter table public.user_library enable row level security;
