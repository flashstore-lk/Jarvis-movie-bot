create table if not exists public.search_history (
  id bigint generated by default as identity primary key,
  whatsapp_jid text not null,
  query text not null,
  result_count integer not null default 0,
  created_at timestamptz not null default now()
);

create index if not exists search_history_created_at_idx
  on public.search_history (created_at desc);

create index if not exists search_history_jid_idx
  on public.search_history (whatsapp_jid);

alter table public.search_history enable row level security;

-- Access is performed by the backend with the service-role key.
-- Never expose SUPABASE_SERVICE_ROLE_KEY in browser/client code.
