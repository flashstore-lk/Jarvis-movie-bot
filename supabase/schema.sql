-- J.A.R.V.I.S. Movie Bot database schema.
-- Run this entire script in Supabase SQL Editor.

create table if not exists public.search_history (
  id bigint generated by default as identity primary key,
  wa_jid text not null,
  query text not null,
  result_count integer not null default 0
    check (result_count >= 0),
  created_at timestamptz not null default now()
);

create index if not exists search_history_created_at_idx
  on public.search_history (created_at desc);

alter table public.search_history enable row level security;

-- Encrypted Baileys authentication state.
-- The service-role key is server-side only. Ciphertext is encrypted by
-- the application with AES-256-GCM before it reaches this table.
create table if not exists public.jarvis_auth_state (
  session_id text not null,
  record_type text not null check (record_type in ('creds', 'key')),
  key_type text not null default '',
  key_id text not null default '',
  ciphertext text not null,
  iv text not null,
  auth_tag text not null,
  updated_at timestamptz not null default now(),
  primary key (session_id, record_type, key_type, key_id)
);

create index if not exists jarvis_auth_state_updated_at_idx
  on public.jarvis_auth_state (updated_at desc);

alter table public.jarvis_auth_state enable row level security;

-- No anon/authenticated policies are intentionally created.
-- The backend accesses these tables with the Supabase service-role key.
